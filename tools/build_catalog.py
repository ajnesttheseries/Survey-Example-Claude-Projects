def is_unusable(u):
    """ลิงก์ที่ Facebook ตัดจนใช้จริงไม่ได้

    นอกจากเครื่องหมาย ... ที่เห็นชัด ยังมีกรณีที่ตัดพอดีตรงขอบ path
    จนดูเหมือน URL สมบูรณ์ แต่ขาดส่วนที่ระบุตัวตนของแอป
    """
    if '...' in u or '\u2026' in u:
        return True
    # Play Store ต้องมี ?id=<package>
    if 'play.google.com/store/apps/details' in u and 'id=' not in u:
        return True
    # Chrome Web Store ต้องมี extension id 32 ตัวอักษร
    if 'chromewebstore.google.com' in u or 'chrome.google.com/webstore' in u:
        if not re.search(r'/[a-p]{32}(?:[/?]|$)', u):
            return True
    # โดเมน .workers.de คือ .workers.dev ที่ถูกตัดตัวสุดท้าย
    if u.rstrip('/').endswith('.workers.de'):
        return True
    return False


